def dividir(a: float, b: float) -> float:
    """Realiza divisão

    :param a: Primeiro Valor
    :type a: float
    :param b: Segundo Valor
    :type b: float
    :return: Retorno do Produto
    :rtype: float
    """
    res = a / b
    return res

print(f"Resultado da divisão: {dividir(10, 2)}")